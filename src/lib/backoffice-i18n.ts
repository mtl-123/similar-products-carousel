export function localizeStatus(value: string, locale: Locale) {
  return statusLabels[locale][value] || value;
}

export function localizeRole(value: string, locale: Locale) {
  const t = backofficeCopy[locale];
  return value === "admin" ? t.adminRole : value === "support" ? t.supportRole : t.affiliateRole;
}

export function localizePayment(value: string, locale: Locale) {
  if (locale === "en") return value;
  return ({ stripe: "Stripe 银行卡", paypal: "PayPal", "apple-pay": "Apple Pay", ach: "美国银行 ACH" } as Record<string, string>)[value] || value;
}

export function localizeChannel(value: string, locale: Locale) {
  const t = backofficeCopy[locale];
  return ({ email: t.emailChannel, web: t.webChannel, chatwoot: "Chatwoot" } as Record<string, string>)[value] || value;
}
