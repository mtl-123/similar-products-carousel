export function localizeProduct(product: Product, locale: Locale) {
  return {
    name: locale === "zh" ? product.name_zh : product.name_en,
    description: locale === "zh" ? product.description_zh : product.description_en,
  };
}

export function localizeCategory(category: string, locale: Locale) {
  if (locale === "en") return category;
  return ({ Travel: "旅行", Bags: "包袋", Everyday: "日常", Accessories: "配件", Electronics: "电子产品" } as Record<string, string>)[category] || category;
}

export function formatCurrency(value: number) {
  return new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" }).format(value);
}
